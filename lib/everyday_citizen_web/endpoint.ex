defmodule EverydayCitizenWeb.Endpoint do
  use Sentry.PlugCapture
  use Phoenix.Endpoint, otp_app: :everyday_citizen

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_everyday_citizen_key",
    signing_salt: "I89Jq1l5",
    same_site: "Lax"
  ]

  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [:peer_data, :x_headers, :user_agent, session: @session_options]],
    longpoll: [connect_info: [:peer_data, :x_headers, :user_agent, session: @session_options]]

  # www. and the Fly hostname redirect to PHX_HOST (production only).
  # Fly's health checks: before the canonical-host redirect, static files,
  # logging and the session (EverydayCitizenWeb.HealthCheck).
  plug EverydayCitizenWeb.HealthCheck

  plug EverydayCitizenWeb.CanonicalHost

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :everyday_citizen,
    gzip: not code_reloading?,
    only: EverydayCitizenWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :everyday_citizen
  end

  plug Phoenix.LiveDashboard.RequestLogger,
    param_key: "request_logger",
    cookie_key: "request_logger"

  plug EverydayCitizenWeb.AiCrawlers
  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library()

  # Error reports carry no request body or cookies, no query string and no IP address.
  plug Sentry.PlugContext,
    remote_address_reader: {EverydayCitizenWeb.SentryScrub, :remote_address},
    body_scrubber: {EverydayCitizenWeb.SentryScrub, :nothing},
    cookie_scrubber: {EverydayCitizenWeb.SentryScrub, :nothing},
    header_scrubber: {EverydayCitizenWeb.SentryScrub, :headers},
    url_scrubber: {EverydayCitizenWeb.SentryScrub, :url}

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug EverydayCitizenWeb.Router
end
